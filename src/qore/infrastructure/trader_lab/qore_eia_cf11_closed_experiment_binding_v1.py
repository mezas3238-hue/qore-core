"""Bind a verified closed EIA association into the *real* CF-11 plan contract.

The Plan is a research-journal value at EXPERIMENT, not a reconstructed history
of earlier CF-11 stages. No replay, economics, CIBO grant or Trader Lab evidence
is manufactured. Caller must authenticate GitHub provenance before binding.
"""
from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass
from datetime import datetime
from typing import Any

from qore.infrastructure.cibo.contracts import (
    CiboEvidenceStatus,
    CiboFunctionalEvidence,
)
from qore.infrastructure.cibo.research_director import (
    CiboResearchPlan,
    CiboResearchStage,
)
from qore.infrastructure.cibo_trader_capability_profile import CiboEvidenceRef
from qore.infrastructure.trader_lab.lifecycle import TraderLabState
from qore.infrastructure.trader_lab.qore_eia_research_science_handoff_v1 import (
    PREREG_COMMIT,
    RESULT_RUN_COMMIT,
    ResearchHandoffError,
    ScientificHandoffReceipt,
    SOURCE_SHA,
    build_handoff_receipt,
)

_REASONS = (
    "diagnostic.no-economic-fills",
    "hypothesis.no-support",
    "holdout.sealed",
    "market.contract-expiry-unknown",
    "market.first-published-at-unknown",
)
_PLAN_CODE = "research.eia.futures-a-f1f2-closure"
_QUESTION_CODE = "research.question.f1f2-directional-probability"
_HYPOTHESIS_CODE = "research.hypothesis.backwardation-predicts-f1-up"
_JOURNAL_SCHEMA = "qore.research.cf11.science-only-closed-experiment.v1"


@dataclass(frozen=True, slots=True)
class Cf11ScientificClosure:
    """Read-only representation; carries no qualified TraderLab candidate."""

    plan: CiboResearchPlan
    receipt_sha256: str
    plan_fingerprint: str
    source_artifact_authenticated_upstream: bool
    scientific_decision: str
    trader_lab_state: TraderLabState
    runnable_trader_created: bool = False
    economic_backtest_performed: bool = False
    demo_eligible: bool = False

    def to_json(self) -> dict[str, Any]:
        return {
            "schema": _JOURNAL_SCHEMA,
            "plan_code": self.plan.plan_code,
            "question_code": self.plan.question_code,
            "hypothesis_code": self.plan.hypothesis_code,
            "stage": self.plan.stage.value,
            "evidence_status": self.plan.evidence.status.value,
            "evidence_reasons": list(self.plan.evidence.reasons),
            "evidence_references": [
                ref.value for ref in self.plan.evidence.evidence_refs
            ],
            "data_requirements": [x.value for x in self.plan.data_requirements],
            "as_of": self.plan.updated_at.isoformat(),
            "receipt_sha256": self.receipt_sha256,
            "plan_fingerprint": self.plan_fingerprint,
            "scientific_decision": self.scientific_decision,
            "source_artifact_authenticated_upstream": (
                self.source_artifact_authenticated_upstream
            ),
            "trader_lab_state": self.trader_lab_state.value,
            "trader_lab_stage_evidence_produced": False,
            "runnable_trader_created": self.runnable_trader_created,
            "economic_backtest_performed": self.economic_backtest_performed,
            "demo_eligible": self.demo_eligible,
            "risk_authority_issued": False,
            "cibo_authority_issued": False,
            "market_provenance_certified": False,
            "fresh_holdout_consumed": False,
            "merge_authorized": False,
        }


def bind_closed_eia_to_cf11(
    original_result: dict[str, Any],
    upstream_receipt: ScientificHandoffReceipt,
    *,
    verified_source: bool,
    as_of: datetime,
) -> Cf11ScientificClosure:
    """Create true CF-11 *value* plan only from authenticated closed results.

    The upstream receipt MUST have been generated by a runner that checked the
    exact original artifact SHA and GitHub prereg ancestry. We independently
    reconstruct all statistics from the given original report so a caller may
    not inject a modified p-value or fake settled evidence.
    """
    if verified_source is not True:
        raise ResearchHandoffError("MISSING_EXTERNAL_GITHUB_ATTESTATION")
    if type(as_of) is not datetime or as_of.tzinfo is None or as_of.utcoffset() is None:
        raise ResearchHandoffError("TIMESTAMP_MUST_BE_TIMEZONE_AWARE")
    if type(upstream_receipt) is not ScientificHandoffReceipt:
        raise ResearchHandoffError("RECEIPT_CLASS_NOT_AUTHENTIC")
    computed = build_handoff_receipt(original_result)
    if computed != upstream_receipt:
        raise ResearchHandoffError("RESULT_OR_RECEIPT_MISMATCH")
    if (
        computed.prereg_commit != PREREG_COMMIT
        or computed.source_run_commit != RESULT_RUN_COMMIT
        or computed.qore_research_classification != "NO_SUPPORT_UNDER_PREREG"
        or computed.cibo_research_contract_stage != CiboResearchStage.EXPERIMENT.value
        or computed.trader_lab_state != TraderLabState.DRAFT.value
    ):
        raise ResearchHandoffError("NOT_CLOSED_EXPERIMENT")
    if (
        computed.trader_lab_stage_evidence_produced
        or computed.has_economic_returns_or_fills
        or computed.fresh_holdout_consumed
        or computed.demo_eligible
        or computed.execution_authority
    ):
        raise ResearchHandoffError("UNAUTHORIZED_PROMOTION")
    receipt_ref = CiboEvidenceRef(
        "evidence:research-eia:science-sha256:" + computed.scientific_receipt_sha256
    )
    requirements = tuple(
        CiboEvidenceRef(f"evidence:source-eia:{name.lower()}:{sha}")
        for name, sha in sorted(SOURCE_SHA.items())
    )
    # Insufficient is intentional, not a misnomer: the statistical result is
    # authentic, but it is NOT owned by an economic or market authority.
    assessment = CiboFunctionalEvidence(
        status=CiboEvidenceStatus.INSUFFICIENT,
        evidence_refs=(receipt_ref,),
        as_of=as_of,
        reasons=_REASONS,
    )
    plan = CiboResearchPlan(
        plan_code=_PLAN_CODE,
        question_code=_QUESTION_CODE,
        hypothesis_code=_HYPOTHESIS_CODE,
        data_requirements=requirements,
        stage=CiboResearchStage.EXPERIMENT,
        evidence=assessment,
        updated_at=as_of,
    )
    canonical = json.dumps(
        plan.logical_values(), sort_keys=True, separators=(",", ":"), allow_nan=False
    )
    return Cf11ScientificClosure(
        plan=plan,
        receipt_sha256=computed.scientific_receipt_sha256,
        plan_fingerprint=hashlib.sha256(canonical.encode("utf-8")).hexdigest(),
        source_artifact_authenticated_upstream=True,
        scientific_decision=computed.qore_research_classification,
        trader_lab_state=TraderLabState.DRAFT,
    )
